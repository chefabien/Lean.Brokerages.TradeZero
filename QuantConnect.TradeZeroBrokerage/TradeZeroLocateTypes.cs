using System;
using System.Collections.Generic;
using System.Globalization;

namespace QuantConnect.Brokerages.TradeZero
{
    /// <summary>
    /// Kind of locate, from the history and inventory field <c>locateType</c>. It decides what you can do with the shares
    /// after a short is covered, and whether they can be sold back.
    /// </summary>
    public enum TradeZeroLocateType
    {
        /// <summary>
        /// <c>locateType</c> 0. Only on refused rows, where TradeZero picked no pool, so you only see it in
        /// <see cref="TradeZeroLocates.GetHistory"/>. Never on an offer or in inventory.
        /// </summary>
        Unknown = 0,

        /// <summary>
        /// <c>locateType</c> 1 or 2 (the same product from two TradeZero pools; the connector maps both here).
        /// The only type offered for an ordinary hard-to-borrow symbol, which is not on the Reg SHO threshold list.
        /// Reusable for the rest of the day: covering a short gives the shares back to <c>available</c>.
        /// The unused part can be sold back, even after covers. <c>/sell</c> string: "Locate".
        /// </summary>
        Locate = 1,

        /// <summary>
        /// <c>locateType</c> 3. Offered for Reg SHO threshold symbols, on the quote's base id.
        /// It behaves like <see cref="Locate"/>: reusable for the day, and the unused part can be sold back.
        /// It usually costs more than SingleUse. <c>/sell</c> string: "PreBorrow".
        /// </summary>
        PreBorrow = 3,

        /// <summary>
        /// <c>locateType</c> 4. Offered for Reg SHO threshold symbols, on the id <c>QuoteReqId + ".SU"</c>.
        /// Used up by the first short sale: covering does NOT give the shares back, so shorting again needs a new locate.
        /// Can only be sold back if no share was ever used to open a short. <c>/sell</c> string: "SingleUse".
        /// </summary>
        SingleUse = 4
    }

    /// <summary>
    /// One locate quote request and every answer TradeZero gave to it. This is what
    /// <see cref="TradeZeroOrderProperties.LocateHandler"/> receives. It is built once all rows of the quote have
    /// settled and never changes afterwards.
    /// </summary>
    public sealed class TradeZeroLocateQuote
    {
        /// <summary>Lean symbol the locate is for</summary>
        public Symbol Symbol { get; }

        /// <summary>
        /// Id of the Lean order that needs the locate.
        /// Null when the quote comes from <see cref="TradeZeroLocates.Locate"/>, which places no order.
        /// </summary>
        public int? LeanOrderId { get; }

        /// <summary>
        /// The Lean order's full quantity, signed as in Lean (negative = sell), including any part that closes a long.
        /// 0 when there is no order.
        /// </summary>
        public decimal OrderQuantity { get; }

        /// <summary>
        /// Shares of this order that open or increase a short position, i.e. the part that needs located shares.
        /// Always positive. 0 when there is no order.
        /// </summary>
        public long ShortQuantity { get; }

        /// <summary>
        /// Located shares the account already held and could short with, read just before the quote:
        /// the sum of <c>available</c> over every type for this symbol. The connector uses these first;
        /// <see cref="RequestedQuantity"/> covers only the rest.
        /// </summary>
        public long AlreadyLocated { get; }

        /// <summary>
        /// Shares the connector asked TradeZero to locate. With an order: ShortQuantity − AlreadyLocated, rounded UP to a
        /// multiple of 100, because TradeZero only quotes lots of 100. Without an order: the quantity passed to
        /// <see cref="TradeZeroLocates.Locate"/>.
        /// </summary>
        public long RequestedQuantity { get; }

        /// <summary>
        /// The quote's base id (TradeZero field <c>quoteReqID</c>), generated by the connector: "LQ{run}.{seq}".
        /// Every history row of this quote has this id (Locate or PreBorrow row) or this id + ".SU" (SingleUse row).
        /// To accept, return an offer: don't build an id yourself.
        /// </summary>
        public string QuoteReqId { get; }

        /// <summary>
        /// The offers you can accept: rows in status 65 (Offered). Never empty.
        /// Sorted by PricePerShare, cheapest first; on equal prices, reusable types (Locate, PreBorrow) come first.
        /// Return one of these objects from the handler to accept it, or null to decline them all.
        /// </summary>
        public IReadOnlyList<TradeZeroLocateOffer> Offers { get; }

        internal TradeZeroLocateQuote(Symbol symbol, int? leanOrderId, decimal orderQuantity, long shortQuantity, long alreadyLocated,
            long requestedQuantity, string quoteReqId, IReadOnlyList<TradeZeroLocateOffer> offers)
        {
            Symbol = symbol;
            LeanOrderId = leanOrderId;
            OrderQuantity = orderQuantity;
            ShortQuantity = shortQuantity;
            AlreadyLocated = alreadyLocated;
            RequestedQuantity = requestedQuantity;
            QuoteReqId = quoteReqId;
            Offers = offers;
        }

        public override string ToString()
        {
            return string.Format(CultureInfo.InvariantCulture, "{0} quote {1}: order {2} qty {3}, short {4}, held {5}, requested {6}, offers [{7}]",
                Symbol?.Value, QuoteReqId, LeanOrderId?.ToString(CultureInfo.InvariantCulture) ?? "-", OrderQuantity, ShortQuantity,
                AlreadyLocated, RequestedQuantity, string.Join("; ", Offers));
        }
    }

    /// <summary>
    /// One offer TradeZero made for a quote: a history row in status 65 (Offered).
    /// Accepting it charges <see cref="TotalCost"/> immediately and adds <see cref="Quantity"/> shares of
    /// <see cref="Type"/> to the inventory.
    /// </summary>
    public sealed class TradeZeroLocateOffer
    {
        /// <summary>Kind of locate offered: Locate, PreBorrow or SingleUse (never Unknown)</summary>
        public TradeZeroLocateType Type { get; }

        /// <summary>
        /// Id of this row, the one the connector sends to <c>/accept</c> if you return this offer:
        /// the quote's base id for Locate/PreBorrow, base id + ".SU" for SingleUse. Informational.
        /// </summary>
        public string QuoteReqId { get; }

        /// <summary>Shares offered (history field <c>locateShares</c>)</summary>
        public long Quantity { get; }

        /// <summary>
        /// True when AlreadyLocated + Quantity ≥ ShortQuantity: accepting it lets the order be sent.
        /// Always true for <see cref="TradeZeroLocates.Locate"/>.
        /// </summary>
        public bool CoversOrder { get; }

        /// <summary>Price per located share in USD (history field <c>locatePrice</c>)</summary>
        public decimal PricePerShare { get; }

        /// <summary>
        /// What accepting costs, in USD: PricePerShare × Quantity. TradeZero deducts it from cash at the accept, even if
        /// the order is later canceled or never fills. The connector adds it to the fee of the order's first fill.
        /// </summary>
        public decimal TotalCost { get; }

        /// <summary>
        /// True for Locate and PreBorrow: after you cover the short, the shares go back to <c>available</c> and can be
        /// shorted again the same day at no extra cost. False for SingleUse: one short sale uses them up.
        /// </summary>
        public bool ReusableAfterCover { get; }

        /// <summary>
        /// True for Locate and PreBorrow: the unused shares can be sold back for credit, even after some were shorted and
        /// covered. False for SingleUse: it can only be sold back if no share was ever used to open a short.
        /// </summary>
        public bool SellBackAfterUse { get; }

        /// <summary>When the row reached status 65, in UTC (history field <c>updatedDate</c>; the local clock when missing)</summary>
        public DateTime OfferedUtc { get; }

        /// <summary>
        /// OfferedUtc + 30 s, when TradeZero expires the offer. The handler must return before then. Computed from
        /// TradeZero's 30 s rule, so it may be off by the clock difference between this machine and TradeZero.
        /// </summary>
        public DateTime ExpiresUtc { get; }

        internal TradeZeroLocateOffer(TradeZeroLocateType type, string quoteReqId, long quantity, bool coversOrder, decimal pricePerShare,
            DateTime offeredUtc)
        {
            Type = type;
            QuoteReqId = quoteReqId;
            Quantity = quantity;
            CoversOrder = coversOrder;
            PricePerShare = pricePerShare;
            TotalCost = pricePerShare * quantity;
            ReusableAfterCover = type != TradeZeroLocateType.SingleUse;
            SellBackAfterUse = type != TradeZeroLocateType.SingleUse;
            OfferedUtc = offeredUtc;
            ExpiresUtc = offeredUtc.AddSeconds(30);
        }

        public override string ToString()
        {
            return string.Format(CultureInfo.InvariantCulture, "{0} {1} {2} @ {3} = {4}{5}", Type, QuoteReqId, Quantity, PricePerShare,
                TotalCost, CoversOrder ? string.Empty : " (does not cover the order)");
        }
    }

    /// <summary>
    /// Located shares of one type for one symbol (a row of the TradeZero locate inventory)
    /// </summary>
    public sealed class TradeZeroLocateInventory
    {
        public Symbol Symbol { get; }

        /// <summary>Locate type of this row: it also tells whether the shares are reusable / sellable after use</summary>
        public TradeZeroLocateType Type { get; }

        /// <summary>Located, not yet shorted nor reserved by a working order</summary>
        public long Available { get; }

        /// <summary>In use by short positions or working orders</summary>
        public long Unavailable { get; }

        /// <summary>Sell-back pending</summary>
        public long ToBeSold { get; }

        /// <summary>Sold back today</summary>
        public long Sold { get; }

        /// <summary>When the inventory was read (UTC)</summary>
        public DateTime UpdatedUtc { get; }

        internal TradeZeroLocateInventory(Symbol symbol, TradeZeroLocateType type, long available, long unavailable, long toBeSold, long sold,
            DateTime updatedUtc)
        {
            Symbol = symbol;
            Type = type;
            Available = available;
            Unavailable = unavailable;
            ToBeSold = toBeSold;
            Sold = sold;
            UpdatedUtc = updatedUtc;
        }

        public override string ToString()
        {
            return $"{Symbol?.Value} {Type}: available={Available} unavailable={Unavailable} toBeSold={ToBeSold} sold={Sold}";
        }
    }

    /// <summary>
    /// A row of today's locate history: a quote row (one per offered type), or a sell-back
    /// </summary>
    public sealed class TradeZeroLocateRecord
    {
        public Symbol Symbol { get; }

        /// <summary>Row id: the quote's base id, base id + ".SU" (SingleUse row), or a sell-back id</summary>
        public string QuoteReqId { get; }

        public TradeZeroLocateType Type { get; }

        /// <summary>
        /// TradeZero <c>locateStatus</c>: 48 sell-back queued, 50 filled, 52 canceled, 54 pending / no shares,
        /// 56 rejected, 65 offered, 67 expired, 81 quoting
        /// </summary>
        public int Status { get; }

        /// <summary>True for a sell-back row (TradeZero reports negative shares)</summary>
        public bool IsSellBack { get; }

        /// <summary>Shares quoted, or sold back (positive)</summary>
        public long Shares { get; }

        /// <summary>Shares filled (positive)</summary>
        public long FilledShares { get; }

        public decimal PricePerShare { get; }

        /// <summary>TradeZero <c>locateError</c> (0 = none): 11 no shares, 14 already pending, 40 under $0.50, 56 easy to borrow, 67 lot of 100…</summary>
        public int ErrorCode { get; }

        public string Text { get; }

        public DateTime? CreatedUtc { get; }

        public DateTime? UpdatedUtc { get; }

        internal TradeZeroLocateRecord(Symbol symbol, string quoteReqId, TradeZeroLocateType type, int status, long shares, long filledShares,
            decimal pricePerShare, int errorCode, string text, DateTime? createdUtc, DateTime? updatedUtc)
        {
            Symbol = symbol;
            QuoteReqId = quoteReqId;
            Type = type;
            Status = status;
            IsSellBack = shares < 0;
            Shares = Math.Abs(shares);
            FilledShares = Math.Abs(filledShares);
            PricePerShare = pricePerShare;
            ErrorCode = errorCode;
            Text = text;
            CreatedUtc = createdUtc;
            UpdatedUtc = updatedUtc;
        }

        public override string ToString()
        {
            return string.Format(CultureInfo.InvariantCulture, "{0} {1} {2}{3} status={4} shares={5} filled={6} price={7} error={8} {9}",
                QuoteReqId, Symbol?.Value, Type, IsSellBack ? " sell-back" : string.Empty, Status, Shares, FilledShares, PricePerShare, ErrorCode, Text);
        }
    }

    /// <summary>
    /// Outcome of an explicit locate action (<see cref="TradeZeroLocates"/>)
    /// </summary>
    public enum TradeZeroLocateStatus
    {
        /// <summary>Sell-back accepted by TradeZero (status 48), settlement pending</summary>
        Pending,
        /// <summary>Locate filled, or sell-back settled</summary>
        Completed,
        /// <summary>The handler declined every offer</summary>
        Declined,
        /// <summary>Refused, by the connector (invalid input) or by TradeZero (see Message)</summary>
        Rejected,
        /// <summary>The accepted offer expired before it was filled</summary>
        Expired,
        /// <summary>No answer from TradeZero within tradezero-locate-timeout-seconds</summary>
        TimedOut
    }

    /// <summary>
    /// Result of <see cref="TradeZeroLocates.Locate"/>, <see cref="TradeZeroLocates.SellBack"/> or one row of
    /// <see cref="TradeZeroLocates.SellBackUnused"/>
    /// </summary>
    public sealed class TradeZeroLocateResult
    {
        public TradeZeroLocateStatus Status { get; }

        /// <summary>Type bought or sold back (Unknown when nothing was)</summary>
        public TradeZeroLocateType Type { get; }

        /// <summary>Shares located, or sold back</summary>
        public long Quantity { get; }

        /// <summary>Locate price per share (Locate only)</summary>
        public decimal PricePerShare { get; }

        /// <summary>Id of the history row (quote or sell-back), null when nothing was sent</summary>
        public string QuoteReqId { get; }

        /// <summary>Why it failed (broker text, or the connector's reason)</summary>
        public string Message { get; }

        /// <summary>True for Completed and Pending</summary>
        public bool IsSuccess => Status is TradeZeroLocateStatus.Completed or TradeZeroLocateStatus.Pending;

        internal TradeZeroLocateResult(TradeZeroLocateStatus status, TradeZeroLocateType type = TradeZeroLocateType.Unknown, long quantity = 0,
            decimal pricePerShare = 0m, string quoteReqId = null, string message = null)
        {
            Status = status;
            Type = type;
            Quantity = quantity;
            PricePerShare = pricePerShare;
            QuoteReqId = quoteReqId;
            Message = message;
        }

        internal static TradeZeroLocateResult Rejected(string message, TradeZeroLocateType type = TradeZeroLocateType.Unknown, string quoteReqId = null)
        {
            return new TradeZeroLocateResult(TradeZeroLocateStatus.Rejected, type, quoteReqId: quoteReqId, message: message);
        }

        public override string ToString()
        {
            return string.Format(CultureInfo.InvariantCulture, "{0} {1} {2} @ {3} {4} {5}", Status, Type, Quantity, PricePerShare, QuoteReqId, Message);
        }
    }
